const contexts = [
  "早晨电梯里碰到同事", "茶水间等咖啡时", "午饭排队时", "会议开始前两分钟", "下班一起等电梯时",
  "第一次和跨部门同事碰面", "同事刚结束一个项目", "同事说这周特别忙", "团队活动刚开始", "线上会议提前进房间时"
];

const prompts = [
  ["观察", "从眼前一个具体细节开场，不急着讲自己"], ["近况", "问一个对方容易接住的近况问题"],
  ["项目", "围绕对方正在做的事问一个具体问题"], ["回应", "接住对方刚说的关键词，再留出继续说的空间"],
  ["感谢", "用一句具体感谢让对方知道你听见了什么"], ["经验", "请对方分享一个小经验，不把它变成请教大会"],
  ["选择", "问一个轻量选择题，让对方容易回答"], ["共鸣", "说出真实但不过度的共同感受"],
  ["延续", "基于上一句话追问一个细节"], ["收束", "自然结束这次交流，并留下下一次可继续的话题"]
];

export const smalltalkScenes = contexts.flatMap((context) => prompts.map(([move, cue]) => ({
  question: `${context}，请用一句自然的${move}回应开始一段不费力的职场闲聊。`,
  move,
  cue
})));
